"""Summarize all generated data and run leakage checks -> data/REPORT.md.

    python scripts/report_data.py
"""
from __future__ import annotations

import json
import sys
from itertools import combinations
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd  # noqa: E402

from rlvr.config import load_config, resolve, task_and_splits  # noqa: E402
from rlvr.io import load_frame  # noqa: E402
from rlvr.tokenizer import CharTokenizer  # noqa: E402


def md_table(df: pd.DataFrame) -> str:
    df = df.reset_index() if df.index.name or isinstance(df.index, pd.MultiIndex) else df
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    cell = lambda v: "" if isinstance(v, float) and pd.isna(v) else str(v)  # noqa: E731
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def counts(col: pd.Series) -> str:
    return " ".join(f"{k}:{v}" for k, v in sorted(col.value_counts().items()))


def degeneracy(df: pd.DataFrame) -> dict:
    """How 'trivial' problems are: answer == input, steps that change nothing,
    and how many distinct answers there are (sorts collapse information)."""
    noop = [any(a == b for a, b in zip([x] + list(s)[:-1], s)) for x, s in zip(df.x, df.steps)]
    return {"ans==x": f"{(df.answer == df.x).mean():.1%}",
            "has_noop_step": f"{pd.Series(noop).mean():.1%}",
            "distinct_ans": f"{df.answer.nunique() / len(df):.0%}"}


def set_summary(name: str, df: pd.DataFrame, tok: CharTokenizer, task) -> dict:
    tgt_len = [len(tok.encode(task.format_target(task.from_dict(r)))) for r in df.sample(min(len(df), 2000), random_state=0).to_dict("records")]
    return {"set": name, "n": len(df), "unique_pid": df.pid.nunique(),
            "depths": counts(df.depth), "groups": counts(df.group),
            "combos": df.funcs.map(tuple).nunique(),
            "max_tgt_tok": max(tgt_len), **degeneracy(df)}


def main():
    cfg = load_config()
    task, splits = task_and_splits(cfg)
    tok = CharTokenizer(task.alphabet)
    data = resolve(cfg["paths"]["data"])
    out = ["# Data report", "", "Generated by `scripts/report_data.py`.", ""]

    # --- task ---------------------------------------------------------------
    out += ["## Functions", "", md_table(pd.DataFrame(json.loads((data / "meta/functions.json").read_text()))), ""]
    out += ["## Held-out ordered pairs (inner -> outer), only in E4", "",
            md_table(pd.DataFrame(json.loads((data / "meta/heldout_pairs.json").read_text()))), ""]

    # --- sets ---------------------------------------------------------------
    sets: dict[str, pd.DataFrame] = {}
    for f in sorted((data / "eval").glob("*/*.jsonl")):
        sets[f"eval/{f.stem}"] = load_frame(f)
    pool = load_frame(data / "rl_pool/candidates.jsonl")
    sets["rl_pool"] = pool
    corpora = {}
    for d in sorted((data / "pretrain").glob("pt-*")):
        c = pd.read_parquet(d / "corpus.parquet")
        corpora[d.name] = c
        sets[f"pretrain/{d.name}/comp"] = c[c.kind == "comp"]
        sets[f"pretrain/{d.name}/atom"] = c[c.kind == "atom"]
    datasets = {f.stem: load_frame(f) for f in sorted((data / "datasets").glob("*.jsonl"))}

    rows = [set_summary(k, v, tok, task) for k, v in sets.items()]
    out += ["## Problem sets", "",
            "`ans==x`: answer equals input. `has_noop_step`: some step leaves its input unchanged. "
            "`distinct_ans`: distinct answers / n.", "",
            md_table(pd.DataFrame(rows)), ""]

    # --- degeneracy by depth on the calibration set (balanced, unfiltered) ---
    calib = sets.get("eval/calib")
    if calib is not None:
        deg = pd.DataFrame([{"depth": d, "group": g, **degeneracy(sub)}
                            for (d, g), sub in calib.groupby(["depth", "group"])])
        out += ["## Degeneracy by depth x group (calib set)", "", md_table(deg), ""]

    # --- leakage --------------------------------------------------------------
    checks = []
    pid_sets = {k: set(v.pid) for k, v in sets.items()}
    pid_sets["pretrain/all"] = set().union(*(set(c.pid) for c in corpora.values())) if corpora else set()
    eval_all = set().union(*(v for k, v in pid_sets.items() if k.startswith("eval/")))
    for a, b in [("pretrain/all", "rl_pool")] + [("pretrain/all", "eval/*"), ("rl_pool", "eval/*")]:
        A = pid_sets[a]
        B = eval_all if b == "eval/*" else pid_sets[b]
        checks.append((f"pid overlap {a} vs {b}", len(A & B), 0))
    eval_names = [k for k in sets if k.startswith("eval/")]
    worst = max((len(pid_sets[a] & pid_sets[b]) for a, b in combinations(eval_names, 2)), default=0)
    checks.append(("max pid overlap between eval sets", worst, 0))
    for k, v in sets.items():
        n_held = int(v.funcs.map(splits.has_heldout_pair).sum())
        want = len(v) if k.endswith("/E4") else 0
        checks.append((f"problems with held-out pair in {k}", n_held, want))
    for k, v in sets.items():
        pool_name = "eval" if k.startswith("eval/") else "rl" if k == "rl_pool" else "pretrain"
        bad = int((v.pid.map(splits.pool_of) != pool_name).sum())
        checks.append((f"problems outside the {pool_name} pool in {k}", bad, 0))
    for name, d in datasets.items():
        checks.append((f"dataset {name} not subset of rl_pool", len(set(d.pid) - pid_sets["rl_pool"]), 0))
        checks.append((f"dataset {name} max depth <= 4 (5-6 reserved for E3)", bool(d.depth.max() <= 4), True))
    recomputed = sum(task.from_dict(r).answer != r["answer"] for r in pool.head(3000).to_dict("records"))
    checks.append(("answers that disagree with recomputation (rl_pool, 3000)", recomputed, 0))
    out += ["## Leakage and consistency checks", "",
            md_table(pd.DataFrame([{"check": c, "value": v, "expected": e, "ok": "yes" if v == e else "**NO**"}
                                   for c, v, e in checks])), ""]

    # --- pretrain corpora ----------------------------------------------------
    if corpora:
        st = [json.loads((data / "pretrain" / n / "stats.json").read_text()) for n in corpora]
        cols = ["run_name", "unique_atoms", "unique_comps", "sequences", "comp_sequences", "target_tokens",
                "total_tokens", "comp_target_token_frac", "atom_count_range", "max_seq_len", "comp_by_group"]
        out += ["## Pretraining corpora", "", md_table(pd.DataFrame(st)[cols]), ""]
        fe = pd.DataFrame({s["run_name"]: s["comp_func_exposure"] for s in st})
        fe.insert(0, "group", ["H" if int(i[1:]) in task.H else "L" for i in fe.index])
        fe.index.name = "func"
        out += ["### Function exposure in compositions (occurrences)", "", md_table(fe), ""]
        if len(corpora) > 1:
            names = list(corpora)
            comp = {n: list(c[c.kind == "comp"].pid) for n, c in corpora.items()}
            nested = all(comp[b][: len(comp[a])] == comp[a] for a, b in zip(names, names[1:])
                         if len(comp[a]) <= len(comp[b]))
            out += [f"Corpora with smaller n_comp are prefixes of larger ones (same seed): **{nested}**", ""]

    # --- RL datasets ----------------------------------------------------------
    drows = []
    for name, d in datasets.items():
        drows.append({"dataset": name, "n": len(d),
                      "depths": counts(d.depth), "groups": counts(d.group),
                      "combos": d.funcs.map(tuple).nunique(), **degeneracy(d)})
    out += ["## RL datasets (structural; p-based ones need labels)", "", md_table(pd.DataFrame(drows)), ""]

    # --- examples --------------------------------------------------------------
    out += ["## Examples (rl_pool, one per depth)", ""]
    for d in range(1, task.max_depth + 1):
        r = pool[pool.depth == d].iloc[0]
        p = task.from_dict(r)
        out += [f"depth {d}, group {p.group}:", "```text", task.format_prompt(p) + task.format_target(p), "```", ""]

    report = data / "REPORT.md"
    report.write_text("\n".join(out))
    bad = [c for c in checks if c[1] != c[2]]
    print(f"wrote {report}; {len(checks) - len(bad)}/{len(checks)} checks ok")
    for c in bad:
        print("  FAILED:", c)


if __name__ == "__main__":
    main()
